from telegram import Update, ReplyKeyboardMarkup
from telegram.ext import Application, CommandHandler, MessageHandler, ContextTypes, filters

TOKEN = "9280766866:AAF-CxbXNgemwfyhQ0i2aclqmcioldeN8HQ"

keyboard = [
    ["🔎 Kino qidirish", "⭐ Mashhur kinolar"],
    ["🎞 Janrlar", "ℹ️ Bot haqida"]
]

menu = ReplyKeyboardMarkup(keyboard, resize_keyboard=True)

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "🎬 CineVerse botiga xush kelibsiz!\n\n"
        "🍿 Kerakli bo‘limni tanlang:",
        reply_markup=menu
    )

async def buttons(update: Update, context: ContextTypes.DEFAULT_TYPE):
    text = update.message.text

    if text == "🔎 Kino qidirish":
        await update.message.reply_text("🔎 Kino nomini yozing!")

    elif text == "⭐ Mashhur kinolar":
        await update.message.reply_text("⭐ Mashhur kinolar tez orada!")

    elif text == "🎞 Janrlar":
        await update.message.reply_text("🎞 Kino janrlari tez orada!")

    elif text == "ℹ️ Bot haqida":
        await update.message.reply_text("🎬 CineVerse — kino ma'lumotlari boti!")

async def main():
    app = Application.builder().token(TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, buttons))

    await app.initialize()
    await app.start()
    await app.updater.start_polling()

    print("🎬 CineVerse ishga tushdi!")

await main()